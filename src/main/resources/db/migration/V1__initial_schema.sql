create table community (
 id bigint generated by default as identity primary key,
 name varchar(255),
 province varchar(255),
 parish varchar(255),
 description varchar(4000)
);
create table user_account (
 id bigint generated by default as identity primary key,
 username varchar(255) not null unique,
 password varchar(255),
 display_name varchar(255),
 role varchar(255),
 community_id bigint,
 active boolean,
 check(role in ('GESTOR','PARTICIPANTE','REVISOR'))
);
create table reviewer_assignment (
 id bigint generated by default as identity primary key,
 reviewer_id bigint,
 community_id bigint,
 unique(reviewer_id,community_id)
);
create table garden (
 id bigint generated by default as identity primary key,
 community_id bigint,
 name varchar(255),
 address varchar(255),
 latitude double precision,
 longitude double precision,
 area double precision,
 design varchar(255),
 soil varchar(255),
 water varchar(255),
 compost varchar(255),
 fence varchar(255),
 unique(community_id)
);
create table plant (
 id bigint generated by default as identity primary key,
 community_id bigint,
 name varchar(255),
 scientific_name varchar(255),
 other_names varchar(255),
 cycle varchar(255),
 traditional_use varchar(4000),
 source varchar(4000)
);
create table garden_activity (
 id bigint generated by default as identity primary key,
 community_id bigint,
 author_id bigint,
 type varchar(255),
 description varchar(4000),
 date date,
 status varchar(255),
 individual_reward integer,
 community_reward integer,
 check(status in ('PENDIENTE','APROBADA','RECHAZADA')),
 check(individual_reward >= 0 and community_reward >= 0)
);
create table participation (
 id bigint generated by default as identity primary key,
 activity_id bigint,
 account_id bigint,
 unique(activity_id,account_id)
);
create table submission (
 id bigint generated by default as identity primary key,
 activity_id bigint,
 author_id bigint,
 description varchar(4000),
 photo_key varchar(255),
 created_at timestamp with time zone
);
create table evidence_review (
 id bigint generated by default as identity primary key,
 activity_id bigint,
 submission_id bigint,
 reviewer_id bigint,
 decision varchar(255),
 observations varchar(4000),
 created_at timestamp with time zone
);
create table point_movement (
 id bigint generated by default as identity primary key,
 activity_id bigint,
 community_id bigint,
 account_id bigint,
 beneficiary_key varchar(255),
 amount integer,
 created_at timestamp with time zone,
 unique(activity_id,beneficiary_key)
);
create table forum_post (
 id bigint generated by default as identity primary key,
 community_id bigint,
 author_id bigint,
 parent_id bigint,
 title varchar(255),
 body varchar(4000),
 hidden boolean,
 created_at timestamp with time zone
);
create table content_report (
 id bigint generated by default as identity primary key,
 post_id bigint,
 reporter_id bigint,
 reason varchar(255),
 status varchar(255),
 moderator_id bigint,
 resolution varchar(255),
 created_at timestamp with time zone
);
create table inventory_item (
 id bigint generated by default as identity primary key,
 community_id bigint,
 name varchar(255),
 category varchar(255),
 quantity integer,
 unit varchar(255),
 check(quantity >= 0)
);
create table calendar_entry (
 id bigint generated by default as identity primary key,
 date date,
 phase varchar(255),
 suggestion varchar(4000),
 source varchar(4000)
);
create table notification (
 id bigint generated by default as identity primary key,
 account_id bigint,
 message varchar(4000),
 seen boolean,
 created_at timestamp with time zone
);
